#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Run Chapter-5 coverage-rate controlled evaluations from a manifest.

The manifest is generated by build_coverage_rate_controlled_layouts.py. This
script intentionally runs jobs sequentially and skips completed metrics files.
"""

from __future__ import annotations

import argparse
import gc
import subprocess
import time
from pathlib import Path

import pandas as pd


def main() -> None:
    repo_root = Path(__file__).resolve().parents[3]
    default_manifest = (
        repo_root
        / "script2_new"
        / "chapter5_layout_optimization"
        / "outputs"
        / "coverage_rate_controlled"
        / "coverage_rate_controlled_run_manifest.csv"
    )

    parser = argparse.ArgumentParser(description="Run coverage-rate controlled Ch5 evaluations.")
    parser.add_argument("--manifest", default=str(default_manifest))
    parser.add_argument("--limit", type=int, default=None, help="Run only the first N unfinished jobs.")
    parser.add_argument("--sleep", type=int, default=60, help="Seconds to sleep between jobs.")
    parser.add_argument("--dry-run", action="store_true", help="Print commands without running training.")
    args = parser.parse_args()

    manifest = pd.read_csv(args.manifest)
    required = {"output_tag", "metrics_file", "command"}
    missing = required - set(manifest.columns)
    if missing:
        raise ValueError(f"Manifest missing columns: {sorted(missing)}")

    unfinished = manifest[~manifest["metrics_file"].map(lambda p: Path(str(p)).exists())].copy()
    if args.limit is not None:
        unfinished = unfinished.head(args.limit)

    if unfinished.empty:
        print("[OK] No unfinished coverage-rate controlled jobs.")
        return

    print(f"[INFO] unfinished jobs selected: {len(unfinished)}")
    for i, row in enumerate(unfinished.itertuples(index=False), start=1):
        tag = str(getattr(row, "output_tag"))
        command = str(getattr(row, "command"))
        print(f"\n[{i}/{len(unfinished)}] {tag}")
        print(command)
        if args.dry_run:
            continue
        result = subprocess.run(command.split(), capture_output=False)
        if result.returncode != 0:
            print(f"[FAILED] {tag}: exit {result.returncode}")
        else:
            print(f"[DONE] {tag}")
        gc.collect()
        time.sleep(args.sleep)


if __name__ == "__main__":
    main()
